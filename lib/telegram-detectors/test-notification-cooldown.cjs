'use strict';
const assert=require('node:assert/strict'),{identity,decide}=require('./notification-cooldown.cjs');
const intent={trade_date:'2026-09-24',symbol:'3055',event_type:'VOLUME_ANOMALY_EVENT',ratio:3,gate:{matches:[{direction:'short'}]}},targetHash='test';
const now='2026-09-24T09:11:00+08:00',base=identity(intent,targetHash),previous={...base,status:'delivered',message_id:1,sent_at:now};
assert.equal(decide({intent,targetHash,now}).allowed,true);
assert.equal(decide({intent,targetHash,previous,now:'2026-09-24T09:13:59.999+08:00'}).allowed,false);
assert.equal(decide({intent,targetHash,previous,now:'2026-09-24T09:14:00+08:00'}).allowed,true);
assert.equal(decide({intent:{...intent,ratio:4.99},targetHash,previous,now}).allowed,false);
assert.equal(decide({intent:{...intent,ratio:5},targetHash,previous,now}).allowed,true);
assert.equal(decide({intent,targetHash,previous:{...previous,tier:8},now}).allowed,false);
assert.notEqual(identity({...intent,gate:{matches:[{direction:'long'}]}},targetHash).key,base.key);
assert.notEqual(identity({...intent,event_type:'PRICE_UP_ANOMALY_EVENT'},targetHash).key,base.key);
assert.notEqual(identity(intent,'other-target').key,base.key);
assert.throws(()=>decide({intent,targetHash,previous:{...previous,status:'failed'},now}),/STATE_INVALID/);
assert.throws(()=>decide({intent,targetHash,previous,now:'2026-09-24T09:10:00+08:00'}),/CLOCK_REGRESSION/);
console.log('PASS success-only cooldown policy: 180s boundary, tiers3/5/8, direction/detector/target separation, invalid state fail closed');
