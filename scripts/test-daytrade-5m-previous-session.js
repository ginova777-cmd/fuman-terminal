"use strict";
const assert=require("node:assert/strict");
const {calculate}=require("./daytrade-intraday-5m-v4");
const {CONTRACT,MODE,normalizeHistory,previousSession}=require("./daytrade-5m-previous-session");
const metadata={symbol:"2330",type:"EQUITY",market:"TSE",timeframe:"5"};
const previous="2026-09-16",today="2026-09-17",asOf=today+"T10:00:00+08:00";
const payload={...metadata,data:Array.from({length:21},(_,i)=>({date:new Date(Date.parse(previous+"T11:40:00+08:00")+i*300000).toISOString(),open:100,high:101,low:99,close:100,volume:20}))};
const prior=normalizeHistory(payload,"2330",previous,asOf,metadata).bars;
const current={...prior.at(-1),trade_date:today,source:"fugle_stock_intraday_candles_timeframe_5",bar_start:today+"T09:00:00+08:00",bar_end:today+"T09:05:00+08:00",candle_time:today+"T09:00:00+08:00"};
const context={contract:CONTRACT,tradeDate:today,previousTradeDate:previous};
const result=calculate([...prior,current],"fixture",asOf,context);
assert.equal(result.length,1);assert.equal(result[0].trade_date,today);
assert.equal(result[0].ma20_5m,100);assert.equal(result[0].previous_ma20_5m,100);
assert.equal(result[0].trend_5m_status,"WAIT_5M_CONFIRMATION");assert.equal(result[0].ma20_warmup_mode,MODE);
assert.equal(result[0].previous_bar_end,prior.at(-1).bar_end);
assert.equal(calculate(prior,"fixture",asOf,context).length,0);
assert.equal(calculate([current],"fixture",asOf,context)[0].trend_5m_status,"DATA_GAP_5M");
assert.equal(calculate([...prior.slice(0,-1),current],"fixture",asOf,context).at(-1).ma20_5m,null);
assert.equal(calculate([...prior,{...current,bar_start:today+"T09:05:00+08:00"}],"fixture",asOf,context).at(-1).ma20_5m,null);
assert.equal(calculate([...prior,current],"fixture",asOf,{...context,previousTradeDate:"2026-09-15"}).at(-1).ma20_5m,null);
assert.equal(calculate([...prior.map(r=>({...r,is_synthetic:true})),current],"fixture",asOf,context).at(-1).ma20_5m,null);
assert.throws(()=>normalizeHistory({...payload,symbol:"2317"},"2330",previous,asOf,metadata),/IDENTITY/);
assert.throws(()=>normalizeHistory(payload,"2330","2026-09-15",asOf,metadata),/DATE/);
assert.throws(()=>normalizeHistory({...payload,data:[payload.data[0],payload.data[0]]},"2330",previous,asOf,metadata),/DUPLICATE/);
assert.throws(()=>normalizeHistory({...payload,data:[{...payload.data[0],close:null}]},"2330",previous,asOf,metadata),/OHLCV/);
assert.throws(()=>normalizeHistory(payload,"2330",previous,previous+"T09:00:00+08:00",metadata),/TIME/);
assert.equal(normalizeHistory({...payload,data:[{...payload.data[0],date:previous+"T13:30:00+08:00"}]},"2330",previous,asOf,metadata).bars.length,0);
assert.equal(previousSession([{market:"TW",trade_date:"2026-09-11",is_open:true},{market:"TW",trade_date:"2026-09-14",is_open:true}],"2026-09-14"),"2026-09-11");
assert.throws(()=>previousSession([],today),/CURRENT_SESSION/);
console.log("PASS previous-session isolation: truthful dates, exact calendar, native source, no auction fabrication, no prior-day publication, no missing-bar bypass, MA20 current/previous, unchanged strict WAIT.");
