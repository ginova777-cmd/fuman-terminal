'use strict';
const assert=require('node:assert/strict');
const {select,nextMonth}=require('../lib/stock-future-standard-selection.cjs');
const base={underlying_symbol:'6257',classification:'STANDARD',classification_verified:true,evidence_trade_date:'2026-10-21',evidence_observed_at:'2026-10-21T00:00:00Z',valid_from:'2026-09-01T00:00:00Z'};
const current={...base,future_symbol:'MQFJ6',contract_month:'2026-10',valid_until:'2026-10-21T05:30:00Z'};
const next={...base,future_symbol:'MQFK6',contract_month:'2026-11',valid_until:'2026-11-18T05:30:00Z'};
const run=(rows,time='2026-10-21T05:29:59Z')=>select(rows,{tradeDate:'2026-10-21',asOf:time})[0];
assert.equal(run([next,current]).selected,'MQFJ6');
assert.equal(run([current,next],'2026-10-21T05:30:00Z').selected,'MQFK6');
assert.equal(run([current],'2026-10-21T05:30:00Z').status,'NO_MATCH');
assert.equal(run([current,next,{...current,future_symbol:'ZZFJ6'}]).status,'MULTIPLE');
assert.equal(run([current,next,{...current,future_symbol:'ZZ1J6',classification:'ADJUSTED'}]).selected,'MQFJ6');
assert.equal(run([current,next,{...current,future_symbol:'ZZFJ6',classification:'MINI'}]).selected,'MQFJ6');
assert.equal(run([{...current,classification_verified:false},next]).status,'MISSING_EVIDENCE');
assert.equal(run([{...current,evidence_trade_date:'2026-10-20'},next]).status,'MISSING_EVIDENCE');
assert.equal(run([{...current,evidence_observed_at:'2026-10-22T00:00:00Z'},next]).status,'MISSING_EVIDENCE');
assert.equal(run([next]).reason,'CURRENT_MONTH_EXPIRY_EVIDENCE_MISSING');
assert.equal(nextMonth('2026-12'),'2027-01');
assert.equal(run([{...current,valid_until:'bad'},next]).status,'MISSING_EVIDENCE');
console.log('PASS: 12 isolated standard/current-month/expiry-boundary/next-month/conflict/evidence checks. No network.');
