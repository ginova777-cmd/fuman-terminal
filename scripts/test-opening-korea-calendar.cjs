"use strict";
const assert=require("node:assert/strict");
const {closure}=require("../lib/opening-report-korea-calendar");
const {applyLeaderFreshness,summarizeReceiptFreshness}=require("../lib/opening-report-asia-freshness");
process.env.FUMAN_MORNING_STAGE="asia_0850";
const old={yahoo_symbol:"005930.KS",ok:true,source_time:"2026-10-02T00:49:00Z",percent:3,close:100,previous_close:97};
const closed=applyLeaderFreshness(old,"2026-10-05");
assert.equal(closed.reason_code,"korea_market_closed");
assert.equal(closed.ok,false);
assert.equal(closed.percent,null);
assert.equal(closed.close,null);
assert.equal(closed.source_gap,false);
assert.equal(summarizeReceiptFreshness({industries:[{leaders:[closed]}]},"2026-10-05").source_gap_count,0);
const stale=applyLeaderFreshness(old,"2026-10-06");
assert.equal(stale.source_gap,true);
assert.equal(stale.ok,false);
assert.equal(closure("2027-10-05"),null);
assert.equal(closure("2026-02-30"),null);
assert.equal(applyLeaderFreshness({...old,yahoo_symbol:"4062.T"},"2026-10-05").source_gap,true);
console.log("PASS holiday excludes stale price; open/unknown dates retain freshness gate; Japanese gap unaffected");
for (const yahoo_symbol of ["005930.KS","4062.T","NVDA"]) {
 const failed=applyLeaderFreshness({yahoo_symbol,ok:false,source_time:"2026-10-06T00:49:00Z",percent:null,source_failure_reason:"http_503"},"2026-10-06");
 assert.equal(failed.source_gap,true);
 assert.equal(failed.reason_code,"http_503");
 const missing=applyLeaderFreshness({yahoo_symbol,ok:true,source_time:"2026-10-06T00:49:00Z",percent:null},"2026-10-06");
 assert.equal(missing.ok,false);
 assert.equal(missing.source_gap,true);
}
const usClosed=applyLeaderFreshness({yahoo_symbol:"NVDA",ok:false,percent:null,no_new_us_session:true,reason_code:"us_market_closed_no_new_session",source_gap:false},"2026-10-05");
assert.equal(usClosed.source_gap,false);
assert.equal(usClosed.ok,false);
