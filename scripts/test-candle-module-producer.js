'use strict';
const assert=require('node:assert/strict');
const {collect}=require('../lib/mother-pool-candle-module-producer');
const {validAll}=require('../lib/verify-module-opening-range');
const identity={trade_date:'2026-09-18',canonical_run_id:'fugle_daytrade_source:20260918:canonical'};
const symbols=['1101','2330'];
const candles=symbols.flatMap(symbol=>Array.from({length:5},(_,i)=>({symbol,tradeDate:identity.trade_date,market:'TSE',source:'fugle-ws-candles',sourceChannel:'candles',candleOrigin:'websocket_candle',synthetic:false,volumeStrategyUsable:true,candleTime:`2026-09-18T09:0${i}:00+08:00`,candleSeenAt:`2026-09-18T09:0${i+1}:00+08:00`,open:100,high:102,low:99,close:101,volume:100})));
const run=raw=>collect({candles:raw,identity,symbols,asOf:'2026-09-18T09:05:01+08:00'});
const plans=run(candles),range=plans.find(p=>p.module_id==='B22');
assert(plans.every(p=>p.rows.length===2&&p.rows.every(r=>r.status==='READY')));
const envelope={by_symbol:Object.fromEntries(range.rows.map(r=>[r.symbol,r.opening_range]))};
assert(validAll(envelope,identity.trade_date,symbols));
assert(!validAll(envelope,identity.trade_date,['1101']));
const missing=run(candles.filter(c=>!(c.symbol==='2330'&&c.candleTime.includes('09:02:'))));
assert.equal(missing[1].rows.find(r=>r.symbol==='2330').status,'DATA_GAP');
assert.equal(missing[1].rows.find(r=>r.symbol==='1101').status,'READY');
const bad=structuredClone(envelope);bad.by_symbol['2330'].bars[0].timestamp='invalid';assert(!validAll(bad,identity.trade_date,symbols));
const cross=structuredClone(envelope);cross.by_symbol['2330'].bars[0].symbol='1101';assert(!validAll(cross,identity.trade_date,symbols));
const price=structuredClone(envelope);price.by_symbol['1101'].high=999;assert(!validAll(price,identity.trade_date,symbols));
const future=run(candles.map(c=>({...c,candleSeenAt:'2026-09-18T10:00:00+08:00'})));assert(future.every(p=>p.rows.every(r=>r.status==='DATA_GAP')));
const pit=require('../lib/verify-mother-pool-point-in-time');
const point={...plans.find(p=>p.module_id==='B23').rows[0],trade_date:identity.trade_date};
assert(pit.verify(point,'2026-09-18T09:05:01+08:00'));
const gap=structuredClone(point);gap.bars_through_event.splice(1,1);assert(!pit.verify(gap,'2026-09-18T09:05:01+08:00'));
const wrongHigh={...point,day_high_so_far:1000};assert(!pit.verify(wrongHigh,'2026-09-18T09:05:01+08:00'));
const unseen=structuredClone(point);unseen.bars_through_event.at(-1).available_at='2026-09-18T09:05:02+08:00';assert(!pit.verify(unseen,'2026-09-18T09:05:01+08:00'));
const stale=collect({candles,identity,symbols,asOf:'2026-09-18T09:06:01+08:00'});assert(stale.find(p=>p.module_id==='B23').rows.every(r=>r.status==='DATA_GAP'));
console.log(JSON.stringify({status:'passed',scope:'isolated',checks:13,production_complete:false}));
