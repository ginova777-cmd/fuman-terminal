'use strict';
const assert = require('node:assert/strict');
const { cutoff, expired, describe } = require('./cleanup-local-calendar');
const now = Date.parse('2026-10-28T16:45:00+08:00');
assert.equal(describe(now).retainFrom, '2026-10-22');
assert.equal(cutoff(now), Date.parse('2026-10-22T00:00:00+08:00'));
assert.equal(expired('2026-10-21T23:59:59.999+08:00', now), true);
assert.equal(expired('2026-10-22T00:00:00+08:00', now), false);
assert.equal(expired('2026-10-22T23:59:59+08:00', now), false);
assert.equal(expired('2026-10-29T00:00:00+08:00', now), false);
assert.equal(expired('invalid', now), false);
assert.equal(describe(Date.parse('2027-01-02T00:00:00+08:00')).retainFrom, '2026-12-27');
assert.equal(describe(Date.parse('2028-03-01T00:00:00+08:00')).retainFrom, '2028-02-24');
assert.throws(() => cutoff(NaN), /invalid/);
assert.throws(() => cutoff(now, 0), /invalid/);
const {compactNotification}=require('./cleanup-extended-retention');
const claim={status:'sent',idempotencyKey:'keep',payloadHash:'keep-hash',channel:'telegram',target:'keep-target',payload:{text:'expired'}};
assert(compactNotification({...claim,recordedAt:'2026-10-21T23:59:59.999+08:00'},now));
assert.equal(compactNotification({...claim,recordedAt:'2026-10-22T00:00:00+08:00'},now),null);
for(const status of ['pending','failed'])assert.equal(compactNotification({...claim,status,recordedAt:'2026-10-01T00:00:00+08:00'},now),null);
const compacted=compactNotification({...claim,recordedAt:'2026-10-01T00:00:00+08:00'},now);
for(const key of ['idempotencyKey','payloadHash','channel','target','status'])assert.equal(compacted[key],claim[key]);
console.log(JSON.stringify({ ok: true, checks: 20, scope: 'isolated-calendar-boundaries', productionActions: false }));
