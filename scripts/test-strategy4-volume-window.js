"use strict";
const assert=require('node:assert/strict');
const {CONTRACT,evaluateVolumeWindow,verifyVolumeEvidence}=require('../lib/strategy4-volume-window');
const dates=['2026-09-09','2026-09-10','2026-09-11','2026-09-14','2026-09-15'];
const rows=dates.map(date=>({date,volume_lots:3000,volume_shares:3000000}));
assert.equal(evaluateVolumeWindow(rows,dates).avgVolume5,3000);
assert.equal(evaluateVolumeWindow(rows.slice(0,4),dates).ok,false);
assert.equal(evaluateVolumeWindow(rows.map((r,i)=>i===2?{...r,date:'2026-09-08'}:r),dates).ok,false);
assert.equal(evaluateVolumeWindow([...rows,rows[0]],dates).ok,false);
assert.equal(evaluateVolumeWindow(rows.map(r=>({...r,volume_lots:3})),dates).ok,false);
assert.equal(evaluateVolumeWindow(rows.map(r=>({...r,volume_lots:null})),dates).avgVolume5,3000);
assert.equal(evaluateVolumeWindow(rows.map(r=>({...r,volume_lots:0,volume_shares:0})),dates).avgVolume5,0);
assert.equal(evaluateVolumeWindow(rows.map(r=>({...r,volume_lots:null,volume_shares:null})),dates).ok,false);
assert.equal(evaluateVolumeWindow(rows.map(r=>({...r,avg_volume_5_lots:1})),dates).avgVolume5,3000);
const filter={contract:CONTRACT,expectedDates:dates,expectedTotal:1,minAvgVolume5:3000,evaluations:[{code:'2330',...evaluateVolumeWindow(rows,dates)}],filtered:[],missing:[]};
assert.deepEqual(verifyVolumeEvidence(filter,dates.at(-1)),[]);
assert(verifyVolumeEvidence({...filter,filtered:[{code:'2330',avgVolume5:1}]},dates.at(-1)).length);
assert(verifyVolumeEvidence(filter,'2026-09-16').length);
assert(verifyVolumeEvidence({...filter,expectedTotal:2},dates.at(-1)).length);
const gap={code:'2330',...evaluateVolumeWindow(rows.slice(0,4),dates)};
assert(verifyVolumeEvidence({...filter,evaluations:[gap]},dates.at(-1)).length);
assert.deepEqual(verifyVolumeEvidence({...filter,evaluations:[gap],missing:[{code:'2330'}]},dates.at(-1)),[]);
console.log('PASS: 15 volume-window regression assertions');
const {normalizeHistory}=require('../lib/strategy4-volume-repair');
const raw={symbol:'2330',data:dates.map(date=>({date,open:10,high:12,low:9,close:11,volume:3000000}))};
assert.equal(normalizeHistory(raw,'2330',dates)[0].volume_lots,3000);
assert.throws(()=>normalizeHistory(raw,'2317',dates));
assert.throws(()=>normalizeHistory({...raw,data:[...raw.data,raw.data[0]]},'2330',dates));
assert.equal(normalizeHistory({...raw,data:[{...raw.data[0],volume:null}]},'2330',dates).length,0);
assert.equal(normalizeHistory({...raw,data:[{...raw.data[0],date:'2026-09-08'}]},'2330',dates).length,0);
console.log('PASS: 5 repair source/date/unit assertions');